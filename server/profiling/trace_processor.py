#: The download: 15 MB from Google's storage. Generous, and bounded.
DOWNLOAD_TIMEOUT_S = 300.0
#: One query over one trace: a base, and the trace's load on top -- measured
#: 1.7 s for 4.1 MB, so about 0.4 s a MB, allowed 1 s a MB.
QUERY_TIMEOUT_S = 60.0
QUERY_S_PER_MB = 1.0


def _platform_key() -> tuple[str, str]:
    machine = platform.machine().lower()
    machine = {"amd64": "x86_64", "arm64": "arm64" if os.uname().sysname == "Darwin"
               else "aarch64"}.get(machine, machine)
    return platform.system().lower(), machine


def binary_path() -> Path:
    # Read at call time, so QUERN_STATE_DIR set by a test applies.
    return config_mod.CONFIG_DIR / "bin" / f"trace_processor_shell-{VERSION}"


def enabled() -> bool:
    """False only when config.json says `"profiles": {"trace_processor": false}`
    -- a literal false. Anything else, including a typo, is the default."""
    raw = config_mod.read_user_config().get("profiles")
    return not (isinstance(raw, dict) and raw.get("trace_processor") is False)


def _download(url: str, dest: Path, timeout: float) -> None:
    """Fetch `url` into `dest`. The default fetcher; tests pass their own."""
    with urllib.request.urlopen(url, timeout=timeout) as r, open(dest, "wb") as f:  # noqa: S310
        shutil.copyfileobj(r, f)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


@dataclass
class Status:
    #: installed, downloading, failed, missing, disabled or unsupported.
    state: str
    version: str = VERSION
    detail: str | None = None

    def as_dict(self) -> dict:
        return {"state": self.state, "version": self.version, "detail": self.detail}


class TraceProcessor:
    """One per server: the binary, its download, and running it."""

    def __init__(self, fetch: Callable[[str, Path, float], None] = _download,
                 platform_key: Callable[[], tuple[str, str]] = _platform_key) -> None:
        self._fetch = fetch
        self._platform_key = platform_key
        self._download: asyncio.Task | None = None
        self._failed: str | None = None

    # -- state ------------------------------------------------------------------

    def status(self) -> Status:
        if not enabled():
            return Status("disabled", detail="config.json's profiles.trace_processor is false")
        if binary_path().is_file() and os.access(binary_path(), os.X_OK):
            return Status("installed")
        if self._download is not None and not self._download.done():
            return Status("downloading", detail=self._size_note())
        if self._platform_key() not in MANIFEST:
            system, machine = self._platform_key()
            return Status("unsupported", detail=f"no trace_processor build for {system} {machine}")
        if self._failed:
            return Status("failed", detail=self._failed)
        return Status("missing")

    def _size_note(self) -> str:
        entry = MANIFEST.get(self._platform_key())
        return f"{entry[2] / 2**20:.0f} MB from Google's perfetto storage" if entry else ""

    def ensure(self) -> Status:
        """Start the download if it is wanted and not under way; return the
        state either way. Never waits for it."""
        if self._download is None:
            self._sweep()
        status = self.status()
        if status.state in ("missing", "failed"):
            self._failed = None
            self._download = asyncio.get_running_loop().create_task(self._fetch_and_verify())
            return Status("downloading", detail=self._size_note())
        return status

    async def wait(self, timeout: float) -> Status:
        """The state after waiting up to `timeout` for a download in progress."""
        task = self._download
        if task is not None and not task.done():
            await asyncio.wait({task}, timeout=timeout)
        return self.status()

    @staticmethod
    def _sweep() -> None:
        """A download cut off by a server stopping leaves its temporary file."""
        for stale in binary_path().parent.glob(".trace_processor-*") \
                if binary_path().parent.is_dir() else []:
            with contextlib.suppress(OSError):
                stale.unlink()

    async def _broken(self, said: str) -> bool:
        """After a query failed: whether the binary itself is broken, not the
        trace -- `--version` failing says so. A broken one is removed and
        said, so the next profile fetches it again rather than every profile
        failing on it for good (review)."""
        try:
            proc = await asyncio.create_subprocess_exec(
                str(binary_path()), "--version",
                stdout=asyncio.subprocess.DEVNULL, stderr=asyncio.subprocess.DEVNULL)
            ok = await asyncio.wait_for(proc.wait(), 15) == 0
        except (OSError, TimeoutError):
            ok = False
        if not ok:
            with contextlib.suppress(OSError):
                binary_path().unlink()
            self._failed = (f"trace_processor {VERSION} would not run ({said}); it was "
                            "removed, and is fetched again on the next profile")
        return not ok

    async def _fetch_and_verify(self) -> None:
        url, sha256, _size = MANIFEST[self._platform_key()]
        dest = binary_path()
        try:
            await asyncio.to_thread(self._install, url, sha256, dest)
            logger.info("trace_processor %s installed at %s", VERSION, dest)
        except asyncio.CancelledError:
            raise
        except Exception as e:  # noqa: BLE001 -- said in every answer that needed it
            self._failed = f"the download of trace_processor {VERSION} failed: {e}"
            logger.warning("%s", self._failed)

    def _install(self, url: str, sha256: str, dest: Path) -> None:
        dest.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(prefix=".trace_processor-", dir=dest.parent)
        os.close(fd)
        tmp = Path(tmp_name)
        try:
            self._fetch(url, tmp, DOWNLOAD_TIMEOUT_S)
            actual = _sha256(tmp)
            if actual != sha256:
                raise ValueError(f"its SHA-256 was {actual}, not the pinned {sha256}; "
                                 "it was deleted, not run")
            tmp.chmod(0o755)
            os.replace(tmp, dest)
        finally:
            with contextlib.suppress(OSError):
                tmp.unlink()

    # -- running ----------------------------------------------------------------

    async def query(self, trace: Path, sql: str) -> list[dict]:
        """Rows of `sql` over `trace`. Raises with trace_processor's own words."""
        if self.status().state != "installed":
            raise RuntimeError(f"trace_processor is {self.status().state}")
        try:
            megabytes = trace.stat().st_size / 2**20
        except OSError:
            megabytes = 0.0
        timeout = QUERY_TIMEOUT_S + megabytes * QUERY_S_PER_MB
        fd, sql_name = tempfile.mkstemp(suffix=".sql")
        with os.fdopen(fd, "w") as f:
            f.write(sql)
        try:
            proc = await asyncio.create_subprocess_exec(
                str(binary_path()), "-q", sql_name, str(trace),
                stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
            try:
                out, err = await asyncio.wait_for(proc.communicate(), timeout)
            except TimeoutError:
                if proc.returncode is None:
                    proc.kill()
                    with contextlib.suppress(Exception):
                        await asyncio.shield(proc.wait())
                raise RuntimeError(f"trace_processor did not answer within {timeout:.0f}s "
                                   f"for a {megabytes:.0f} MB trace") from None
            except BaseException:
                if proc.returncode is None:
                    proc.kill()
                    with contextlib.suppress(Exception):
                        await asyncio.shield(proc.wait())
                raise
        finally:
            with contextlib.suppress(OSError):
                os.unlink(sql_name)
        if proc.returncode != 0:
            said = err.decode(errors="replace").strip().splitlines()
            words = said[-1] if said else "no output"
            if proc.returncode < 0 or not said:
                await self._broken(f"exit {proc.returncode}: {words}")
            raise RuntimeError(f"trace_processor failed (exit {proc.returncode}): {words}")
        return parse_csv(out.decode(errors="replace"))


def parse_csv(text: str) -> list[dict]:
    """trace_processor's `-q` output: CSV with a quoted header, values quoted
    or bare, `[NULL]` for null. The last result only, as it prints it."""
    lines = [ln for ln in text.splitlines() if ln.startswith('"') or ln[:1].isdigit()
             or ln.startswith("-") or ln.startswith("[")]
    if not lines:
        return []
    rows = list(csv.reader(io.StringIO("\n".join(lines))))
    header, body = rows[0], rows[1:]
    out = []
    for row in body:
        if len(row) != len(header):
            continue
        out.append({k: _value(v) for k, v in zip(header, row, strict=True)})
    return out


def _value(raw: str) -> object:
    if raw == "[NULL]":
        return None
    for kind in (int, float):
        try:
            return kind(raw)
        except ValueError:
            pass
    return raw
