"""trace_processor: Google's reader for perfetto traces, fetched on first use (#245).

An Android profile is a perfetto trace. Without trace_processor quern can say
what it reads off the device -- frames from gfxinfo, hangs InputDispatcher
logged, CPU from /proc -- and hand the trace over for ui.perfetto.dev. With it
the summary reads the trace itself: how long the app left input unanswered,
how long each frame took, which slices were slowest.

**Downloaded on first use, and said.** The first Android profile that could use
it starts the download in the background, while it records, so the stop is
not held up by it. Every answer that depends on it says what state it is in:
installed, downloading, failed and why, or turned off. Nothing happens behind
the caller's back.

**Pinned, and checked.** One version, from perfetto's own release manifest
(tools/release/roll-prebuilts, v59.1): each platform's URL and SHA-256. A file
whose checksum differs is deleted and reported, never run. The pin is what
makes "it was verified" mean something; the agent cannot check a binary any
better than this does.

**Off switch.** `"profiles": {"trace_processor": false}` in config.json means
it is neither downloaded nor used -- for a machine offline or not allowed to
fetch binaries, or anyone who would rather it was not run. Off is off: an
already-installed copy is not used either (live: it was, which is not what a
person turning it off would expect).
"""

from __future__ import annotations

